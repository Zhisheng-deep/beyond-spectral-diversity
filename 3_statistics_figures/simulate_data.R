# =============================================================================
# Simulated data for the statistical analyses and main-text figures (Fig. 4-12)
#
# The field data of the study are not part of this repository. This script
# generates simulated data with the sampling design of the paper, from which
# every script in this folder runs. The data come from a random model: they
# demonstrate the analytical workflow and reproduce the layout of the figures,
# but the statistical results obtained from them differ from those of the
# paper.
#
# Design (Section 2.2 of the paper)
#   10 management units (6 under grazing, 4 under fencing) with 47 plots of
#   1.5 m x 1.5 m. Each plot is divided into nine 0.5 m x 0.5 m quadrats in a
#   3 x 3 grid and four overlapping 1 m x 1 m subplots assembled from four
#   adjacent quadrats.
#
# Random model (fixed seed)
#   Parameters are drawn at random for each management unit, independently of
#   the management regime, and the two maps (deep learning species map and
#   spectral cluster map) are generated by the same random procedure.
#   1. Field community of each plot: species from a regional pool, numbers of
#      individuals from a rank-abundance curve with a random decay, and
#      heights. Individuals are distributed over the nine quadrats.
#   2. Each quadrat: the sunlight-exposed species are the taller and more
#      abundant species present; fractional vegetation cover (FVC) gives the
#      number of valid pixels (out of 25 x 25 pixels of 2 cm).
#   3. Maps of each quadrat: each sunlight-exposed species enters the map with
#      a random probability (drawn per unit and map), random additional labels
#      are added, and the valid pixels are divided among the labels with random
#      weights. Labels of the species map are species of the regional pool;
#      labels of the cluster map are clusters of the plot, a random one-to-one
#      relabelling of the species within each plot. Each pixel of the species
#      map receives a simulated spectrum of its label with random intra-species
#      variation.
#   4. Aggregation: every sampling unit (quadrat, subplot, plot, intermediate
#      window, pooled plots) is a set of quadrats. Individuals and pixels are
#      summed, species and labels are taken as the union, and all metrics are
#      computed from them with the definitions of the paper (Table S1;
#      dominance metrics as in ../2_dominance_metrics). Clusters are not
#      comparable across plots, and pooled plots have no cluster metrics.
#   By construction, Top1 >= Top2 >= Top3, Top12 = Top1 + Top2,
#   Top123 = Top1 + Top2 + Top3 <= 1, Top1 >= 1/SR, and the species richness of
#   a sampling unit is at least that of any unit it contains.
#
# Output (in output_dir)
#   analysis_table.csv   : scales 0.5m, 1m, 1.5m (n = 423, 188, 47)
#   multiscale_table.csv : the intermediate windows 0.5x1m and 1x1.5m and the
#                          pooled plots pool2 and pool3 (n = 564, 188, 92, 94);
#                          member_plots lists the plots of each row (Plot15,
#                          separated by ";") and n_plots their number
#
# Usage   : Rscript simulate_data.R [output_dir]
# Default : output_dir = "../data/simulated"
# Runtime : about two minutes
# =============================================================================

args    <- commandArgs(trailingOnly = TRUE)
out_dir <- if (length(args) >= 1) args[1] else "../data/simulated"

set.seed(20261031)

# ---- design -----------------------------------------------------------------
UNITS <- data.frame(
  Unit       = 1:10,
  Management = c(rep("grazing", 6), rep("fencing", 4)),
  n_plots    = c(2, 5, 5, 5, 5, 5, 6, 5, 4, 5)
)
QUAD_PX <- 25L * 25L     # pixels per 0.5 m quadrat at 2 cm
N_REG   <- 60L           # species in the regional pool
N_BAND  <- 20L           # simulated spectral bands

# Quadrats are numbered 1-9 row by row from the upper left of the plot. Every
# sampling unit within a plot is a set of quadrats; the names are the Window
# labels of the data tables (H, horizontal; V, vertical).
WINDOWS <- list(
  "0.5m"   = setNames(as.list(1:9), 1:9),
  "0.5x1m" = list(H1 = c(1, 2), H2 = c(2, 3), H3 = c(4, 5), H4 = c(5, 6),
                  H5 = c(7, 8), H6 = c(8, 9), V1 = c(1, 4), V2 = c(4, 7),
                  V3 = c(2, 5), V4 = c(5, 8), V5 = c(3, 6), V6 = c(6, 9)),
  "1m"     = list("1" = c(1, 2, 4, 5), "2" = c(2, 3, 5, 6),            # upper left, upper right,
                  "3" = c(4, 5, 7, 8), "4" = c(5, 6, 8, 9)),           # lower left, lower right
  "1x1.5m" = list(H1 = 1:6, H2 = 4:9, V1 = c(1, 2, 4, 5, 7, 8), V2 = c(2, 3, 5, 6, 8, 9)),
  "1.5m"   = list("0" = 1:9)
)

# ---- regional species pool ------------------------------------------------------
freq   <- rlnorm(N_REG, 0, 1)                 # regional frequency
height <- rlnorm(N_REG, log(15), 0.5)         # mean height (cm)
spec_mean <- t(sapply(seq_len(N_REG), function(s) {
  x <- rlnorm(N_BAND, 0, 0.3) * seq(0.5, 1.5, length.out = N_BAND)
  x / sqrt(sum(x^2))                          # brightness-normalized
}))

# ---- random parameters per management unit ----------------------------------------
n_u <- nrow(UNITS)
UNIT_PAR <- data.frame(
  S_mean = runif(n_u, 8, 24),        # mean number of species per plot
  decay  = runif(n_u, 0.2, 1.2),     # decay of the rank-abundance curve
  h_sd   = runif(n_u, 0.2, 0.7),     # variation in height among species
  fvc    = runif(n_u, 0.4, 0.9),     # mean FVC
  hidden = runif(n_u, 0.1, 0.6),     # largest fraction of species overtopped in a quadrat
  a_sd   = runif(n_u, 0.02, 0.10)    # intra-species spectral variation
)
MAP_PAR <- lapply(c(DL = "DL", SC = "SC"), function(m) data.frame(
  keep   = runif(n_u, 0, 1),         # probability that an exposed species enters the map
  extra  = runif(n_u, 0, 1),         # mean number of additional labels per quadrat
  w_sd   = runif(n_u, 0.3, 1.5)      # spread of the pixel weights of the labels
))

# ---- metric functions ---------------------------------------------------------
top_metrics <- function(counts) {
  counts <- counts[counts > 0]
  share  <- unname(sort(counts / sum(counts), decreasing = TRUE))
  top    <- c(share, 0, 0, 0)[1:3]            # unoccupied ranks have a share of 0
  c(Top1 = top[1], Top2 = top[2], Top3 = top[3],
    Top12 = top[1] + top[2], Top123 = top[1] + top[2] + top[3])
}
shannon <- function(counts) {
  p <- counts[counts > 0] / sum(counts)
  -sum(p * log(p))
}
beta_sim <- function(pa) {                    # multiple-site Simpson dissimilarity
  m <- 0
  for (i in 1:(nrow(pa) - 1)) for (j in (i + 1):nrow(pa))
    m <- m + min(sum(pa[i, ] & !pa[j, ]), sum(pa[j, ] & !pa[i, ]))
  m / (sum(pa) - sum(colSums(pa) > 0) + m)
}
cv_index  <- function(X) mean(apply(X, 2, sd) / colMeans(X))
cha_index <- function(X) {
  mu <- colMeans(X)
  mean(apply(X, 1, function(r) {
    h <- chull(mu, r); x <- mu[h]; y <- r[h]
    abs(sum(x * c(y[-1], y[1]) - c(x[-1], x[1]) * y)) / 2
  }))
}
rao_index  <- function(X) 2 * sum(dist(X)) / nrow(X)^2
sdiv_index <- function(X, lab) {              # weighted by canopy share
  idx <- split(seq_len(nrow(X)), lab)
  idx <- idx[lengths(idx) >= 2]               # a CV needs at least two pixels
  w   <- lengths(idx) / sum(lengths(idx))
  sum(w * sapply(idx, function(i) cv_index(X[i, , drop = FALSE])))
}

# ---- plots ----------------------------------------------------------------------
plots <- do.call(rbind, lapply(seq_len(n_u), function(u)
  data.frame(Unit = UNITS$Unit[u], Management = UNITS$Management[u],
             Plot = seq_len(UNITS$n_plots[u]))))
plots$Plot15 <- paste(plots$Unit, plots$Plot, sep = "_")

# labels of one map in one quadrat, divided among n_valid pixels
map_quadrat <- function(exposed_labels, other_labels, par, n_valid) {
  lab <- exposed_labels[runif(length(exposed_labels)) < par$keep]
  lab <- unique(c(lab, sample(other_labels, min(rpois(1, par$extra), length(other_labels)))))
  if (length(lab) == 0) lab <- sample(c(exposed_labels, other_labels), 1)
  if (length(lab) > n_valid) lab <- sample(lab, n_valid)
  n <- 1L + as.vector(rmultinom(1, n_valid - length(lab), rlnorm(length(lab), 0, par$w_sd)))
  rep(lab, n)
}

simulate_plot <- function(p) {
  u  <- plots$Unit[p]
  up <- UNIT_PAR[u, ]

  # 1. field community
  S  <- as.integer(min(max(round(rnorm(1, up$S_mean, 3)), 4), N_REG))
  sp <- sample(N_REG, S, prob = freq)                       # ordered by abundance rank
  ab <- 1L + as.vector(rmultinom(1, rpois(1, 700),
                                 exp(-up$decay * rlnorm(1, 0, 0.25) * seq_len(S)) * rlnorm(S, 0, 0.5)))
  h_sp <- height[sp] * rlnorm(S, 0, up$h_sd)
  occ <- pmin(pmin(9L, pmax(1L, rbinom(S, 9, pmin(0.95, 0.15 + 0.12 * log(ab))))), ab)
  n_q <- matrix(0L, 9, S)
  for (s in seq_len(S)) {
    q <- sample(9, occ[s])
    n_q[q, s] <- 1L + as.vector(rmultinom(1, ab[s] - occ[s], rgamma(occ[s], 1)))
  }
  for (q in which(rowSums(n_q) == 0)) {                    # no quadrat without plants
    donor <- which(n_q[, 1] >= 2)[1]
    n_q[q, 1] <- 1L; n_q[donor, 1] <- n_q[donor, 1] - 1L
  }
  h_q <- sweep(matrix(rlnorm(9 * S, 0, 0.1), 9, S), 2, h_sp, "*")

  # cluster labels of the plot: a random one-to-one relabelling of the species
  cluster <- sample(N_REG)

  # 2.-3. quadrats
  quads <- lapply(1:9, function(q) {
    pres    <- which(n_q[q, ] > 0)
    score   <- log(n_q[q, pres]) + log(h_q[q, pres]) + rnorm(length(pres), 0, 0.7)
    exposed <- pres[score >= quantile(score, runif(1, 0, up$hidden)) | rank(-score) <= 1]
    fvc     <- min(max(rnorm(1, up$fvc, 0.1), 0.1), 1)
    n_valid <- max(rbinom(1, QUAD_PX, fvc), 1L)
    other <- setdiff(seq_len(N_REG), sp[exposed])
    pred  <- map_quadrat(sp[exposed], other, MAP_PAR$DL[u, ], n_valid)
    clus  <- map_quadrat(cluster[sp[exposed]], cluster[other], MAP_PAR$SC[u, ], n_valid)
    m <- length(pred)
    X <- spec_mean[pred, , drop = FALSE] * (1 + up$a_sd * matrix(rnorm(m * N_BAND), m))
    X <- X / sqrt(rowSums(X^2))
    list(exposed = exposed, fvc = fvc, pred = pred, clus = clus, X = X)
  })

  list(sp = sp, n_q = n_q, h_q = h_q, quads = quads)
}

cat("Simulating", nrow(plots), "plots ...\n")
sims <- lapply(seq_len(nrow(plots)), simulate_plot)

# ---- 5. metrics of a sampling unit ---------------------------------------------
# members: list of c(plot index, quadrats); spectral = compute the spectral
# indices; within_plot = the unit lies within one plot (clusters comparable)
unit_row <- function(members, spectral, within_plot) {
  ab <- integer(0); hs <- numeric(0); hw <- numeric(0)
  exposed <- integer(0); fvc <- numeric(0); pred <- integer(0)
  X <- NULL; clus <- integer(0); pa <- NULL
  for (m in members) {
    s <- sims[[m$p]]
    for (q in m$q) {
      present <- which(s$n_q[q, ] > 0)
      ab  <- c(ab, setNames(s$n_q[q, present], s$sp[present]))
      hs  <- c(hs, setNames(s$h_q[q, present], s$sp[present]))
      hw  <- c(hw, pmin(s$n_q[q, present], 3L))             # heights measured on <= 3 plants
      exposed <- c(exposed, s$sp[s$quads[[q]]$exposed])
      fvc  <- c(fvc, s$quads[[q]]$fvc)
      pred <- c(pred, s$quads[[q]]$pred)
      clus <- c(clus, s$quads[[q]]$clus)
      if (spectral) X <- rbind(X, s$quads[[q]]$X)
      row <- integer(N_REG); row[s$sp[present]] <- 1L
      pa  <- rbind(pa, row)
    }
  }
  ab_sp <- tapply(ab, names(ab), sum)
  h_sp  <- (tapply(hs * hw, names(hs), sum) / tapply(hw, names(hs), sum))[names(ab_sp)]
  p_ab  <- ab_sp / sum(ab_sp)
  h_mean <- sum(p_ab * h_sp)
  ob  <- top_metrics(ab_sp)
  dl  <- top_metrics(table(pred))
  out <- c(
    Observed_SR         = length(ab_sp),
    Observed_Visible_SR = length(unique(exposed)),
    Observed_Shannon    = shannon(ab_sp),
    DL_SR               = length(unique(pred)),
    DL_Shannon          = shannon(table(pred)),
    setNames(dl, paste0("DL_", names(dl))),
    setNames(ob, paste0("OB_", names(ob))),
    Rare_Species_Ratio  = mean(p_ab < 0.01),
    FVC                 = mean(fvc),
    Height_Mean         = h_mean,
    Height_CV           = sqrt(sum(p_ab * (h_sp - h_mean)^2)) / h_mean,
    Turnover            = if (length(members) == 1 && nrow(pa) %in% c(4, 9)) beta_sim(pa) else NA
  )
  if (within_plot) {
    sc  <- top_metrics(table(clus))
    out <- c(out, SSR_km_z = length(unique(clus)), SC_Shannon = shannon(table(clus)),
             setNames(sc, paste0("SC_", names(sc))))
  } else {
    out <- c(out, SSR_km_z = NA, SC_Shannon = NA,
             setNames(rep(NA, 5), paste0("SC_", c("Top1", "Top2", "Top3", "Top12", "Top123"))))
  }
  if (spectral) {
    out <- c(out, Intra_Species_SDiv = sdiv_index(X, pred),
             CV = cv_index(X), CHA = cha_index(X), "Rao'S Q" = rao_index(X))
  }
  out
}

cat("Computing the metrics of all sampling units ...\n")
rows <- list()
for (sc in names(WINDOWS)) {
  for (p in seq_len(nrow(plots))) {
    for (w in seq_along(WINDOWS[[sc]])) {
      met <- unit_row(list(list(p = p, q = WINDOWS[[sc]][[w]])),
                      spectral = sc %in% c("0.5m", "1m", "1.5m"), within_plot = TRUE)
      rows[[length(rows) + 1]] <- data.frame(
        Scale = sc, Management = plots$Management[p], Unit = plots$Unit[p],
        Plot = plots$Plot[p], Plot15 = plots$Plot15[p],
        Window = names(WINDOWS[[sc]])[w],
        member_plots = plots$Plot15[p], n_plots = 1L,
        t(met), check.names = FALSE)
    }
  }
}
for (k in 2:3) {
  for (u in UNITS$Unit) {
    idx <- which(plots$Unit == u)
    if (length(idx) < k) next
    cmb <- combn(idx, k)
    for (j in seq_len(ncol(cmb))) {
      mem <- lapply(cmb[, j], function(p) list(p = p, q = 1:9))
      met <- unit_row(mem, spectral = FALSE, within_plot = FALSE)
      rows[[length(rows) + 1]] <- data.frame(
        Scale = paste0("pool", k), Management = UNITS$Management[u], Unit = u,
        Plot = NA, Plot15 = "", Window = paste(plots$Plot15[cmb[, j]], collapse = ";"),
        member_plots = paste(plots$Plot15[cmb[, j]], collapse = ";"), n_plots = k,
        t(met), check.names = FALSE)
    }
  }
}
all_rows <- do.call(rbind, lapply(rows, function(r) {
  miss <- setdiff(names(rows[[1]]), names(r)); r[miss] <- NA; r[names(rows[[1]])]
}))
num <- c("Observed_SR", "Observed_Visible_SR", "DL_SR", "SSR_km_z")
all_rows[num] <- lapply(all_rows[num], as.integer)

# ---- checks of the built-in relationships ----------------------------------------
chk <- function(ok, msg) if (length(ok) == 0 || !all(ok, na.rm = TRUE)) stop("Check failed: ", msg)
for (pre in c("DL_", "OB_", "SC_")) {
  t1 <- all_rows[[paste0(pre, "Top1")]]; t2 <- all_rows[[paste0(pre, "Top2")]]
  t3 <- all_rows[[paste0(pre, "Top3")]]
  chk(t1 >= t2 & t2 >= t3, paste(pre, "rank order"))
  chk(abs(all_rows[[paste0(pre, "Top12")]] - (t1 + t2)) < 1e-12, paste(pre, "Top12"))
  chk(abs(all_rows[[paste0(pre, "Top123")]] - (t1 + t2 + t3)) < 1e-12 &
      all_rows[[paste0(pre, "Top123")]] <= 1 + 1e-12, paste(pre, "Top123"))
}
chk(all_rows$DL_Top1 >= 1 / all_rows$DL_SR - 1e-12, "DL Top1 >= 1/SR")
chk(all_rows$OB_Top1 >= 1 / all_rows$Observed_SR - 1e-12, "OB Top1 >= 1/SR")
chk(all_rows$Observed_Visible_SR <= all_rows$Observed_SR, "visible <= full SR")
q05 <- all_rows[all_rows$Scale == "0.5m", ]
for (sc in c("0.5x1m", "1m", "1x1.5m", "1.5m")) {
  big <- all_rows[all_rows$Scale == sc, ]
  for (i in seq_len(nrow(big))) {
    qs  <- WINDOWS[[sc]][[big$Window[i]]]
    sub <- q05[q05$Plot15 == big$Plot15[i] & q05$Window %in% qs, ]
    chk(big$Observed_SR[i] >= max(sub$Observed_SR) & big$DL_SR[i] >= max(sub$DL_SR),
        paste("nesting at", sc))
  }
}
pl <- all_rows[all_rows$Scale == "1.5m", ]
for (i in which(all_rows$n_plots > 1)) {
  mem <- strsplit(all_rows$member_plots[i], ";")[[1]]
  chk(all_rows$Observed_SR[i] >= max(pl$Observed_SR[pl$Plot15 %in% mem]), "pooled SR")
}

